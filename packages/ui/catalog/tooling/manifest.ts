/** Builds catalog/manifest.json from the repository (deterministic: no timestamps). */
import { join } from 'node:path'
import {
  componentSnapshotHashes,
  componentSourceHash,
  effectiveStatus,
  loadTrustedKeys,
  parseReviewRecord,
  uiPaths,
  verifyRecordApproval,
} from '../approval/index.ts'
import type { CatalogManifest, ManifestComponent } from '../manifest-types.ts'
import { cssVariablesOf, readInventory } from './inventory.ts'
import { readProps } from './props.ts'
import { defaultUsageScope, scanUsage, type UsageScope } from './usage.ts'

export const MANIFEST_COMMENT =
  'Generated by `npm run manifest --workspace @guanxi/ui` (packages/ui/catalog/tooling/manifest.ts). Do not edit.'

export function buildManifest(uiRoot: string, scope: UsageScope = defaultUsageScope(join(uiRoot, '..', '..'))): CatalogManifest {
  const inventory = readInventory(uiRoot)
  const paths = uiPaths(uiRoot)
  const keys = loadTrustedKeys(paths.trustedKeys)
  const trusted = keys.ok ? keys.file.keys : []
  const usage = scanUsage(scope)
  const publicFolders = inventory.folders.filter((folder) => inventory.publicFolders.includes(folder.id))
  const props = readProps(uiRoot, publicFolders)
  const components: ManifestComponent[] = publicFolders.map((folder) => {
    const parsed = folder.reviewJson === null ? null : parseReviewRecord(folder.reviewJson, folder.id)
    const record = parsed?.ok ? parsed.record : null
    const current = {
      sourceHash: componentSourceHash(folder.dir),
      snapshotHashes: componentSnapshotHashes(paths.snapshots, folder.id),
    }
    const verdict = record ? verifyRecordApproval(record, trusted) : { state: 'absent' as const }
    const signature = verdict.state === 'invalid' ? 'invalid' : verdict.state === 'valid' ? 'valid' : 'absent'
    const files = new Set<string>()
    for (const name of folder.valueExports) for (const file of usage.get(name) ?? []) files.add(file)
    for (const file of usage.get('*') ?? []) files.add(file)
    return {
      id: folder.id,
      title: folder.docs?.title ?? folder.id,
      level: folder.docs?.level ?? 'primitive',
      folder: `src/components/${folder.id}`,
      exports: [...folder.exports].sort(),
      componentExports: folder.valueExports.filter((name) => /^[A-Z]/.test(name)).sort(),
      states: folder.docs?.states ?? [],
      stories: folder.stories.map((story) => story.name ?? story.exportName),
      props: props.get(folder.id) ?? {},
      cssVariables: cssVariablesOf(folder),
      sourceHash: current.sourceHash,
      snapshotHashes: current.snapshotHashes,
      storedStatus: record?.status ?? 'draft',
      signature,
      status: record ? effectiveStatus(record, signature, current) : 'invalid',
      usage: { count: files.size, files: [...files].sort() },
      since: folder.docs?.since ?? null,
    }
  })
  return { $comment: MANIFEST_COMMENT, version: 1, components: components.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0)) }
}

export function serialiseManifest(manifest: CatalogManifest): string {
  return `${JSON.stringify(manifest, null, 2)}\n`
}
