const header = '/* Generated by npm run tokens:build. Do not edit. */\n'

export function renderCSS(contexts, declarations, diff) {
  const defaults = contexts['light/compact/full']
  const themes = ['light', 'dark', 'light-hc', 'dark-hc']
  const themedNames = new Set(themes.flatMap(name => diff(contexts[`${name}/compact/full`], defaults).map(t => t.name)))
  const block = (selector, tokens) => `${selector} {\n${declarations(tokens)}\n}\n`
  const theme = (name, selector) => block(selector, contexts[`${name}/compact/full`].filter(t => themedNames.has(t.name)))
  let css = header + '@import "../fonts/fonts.css";\n' + block(':root', defaults)
  // Environment tokens (FOUNDATIONS §3): the device's safe-area insets, 0 where there are none.
  // DTCG dimensions are px or rem only, so the pipeline emits these from a fixed list; product CSS
  // reads them as var(--safe-area-inset-*) and never writes env() itself.
  css += `:root {\n${['top', 'right', 'bottom', 'left'].map(side => `  --safe-area-inset-${side}: env(safe-area-inset-${side}, 0px);`).join('\n')}\n}\n`
  for (const name of themes) css += theme(name, `[data-theme="${name}"]${name === 'dark' ? ', :root.dark:not([data-theme])' : ''}`)

  const densityNames = new Set(['font.text.size', 'control.height', 'row.height', 'panel.padding', 'pane.gap'])
  for (const density of ['compact', 'comfortable']) css += block(`[data-density="${density}"]`, contexts[`light/${density}/full`].filter(t => densityNames.has(t.name)))
  for (const motion of ['full', 'reduced']) css += block(`[data-motion="${motion}"]`, contexts[`light/compact/${motion}`].filter(t => t.name.startsWith('motion.')))

  // An absent attribute uses the resolver's Light default (and the legacy .dark class).
  // Only explicit system mode follows OS colour scheme, independently of other modifiers.
  css += `@media (prefers-color-scheme: dark) {\n${theme('dark', ':root[data-theme="system"]')}}\n`
  css += '@media (prefers-contrast: more) {\n'
  css += theme('light-hc', ':root:not(.dark):not([data-theme]), :root[data-theme="system"], :root[data-theme="light"]')
  css += theme('dark-hc', ':root.dark:not([data-theme]), :root[data-theme="dark"]')
  css += `@media (prefers-color-scheme: dark) {\n${theme('dark-hc', ':root[data-theme="system"]')}}\n}\n`
  css += `@media (prefers-reduced-motion: reduce) {\n${block(':root:not([data-motion="full"])', contexts['light/compact/reduced'].filter(t => t.name.startsWith('motion.')))}}\n`

  function material(level, selector, strong = false) {
    const prefix = `--material-${strong ? 'strong-' : ''}${level}`
    return `${selector} {\n  --material-background: color-mix(in srgb, var(--material-${level}-fill) calc(var(${prefix}-fill-opacity) * 100%), transparent);\n  --material-backdrop: blur(var(${prefix}-blur)) saturate(var(${prefix}-saturation));\n  --material-grain: var(--material-${level}-grain-opacity);\n  --material-border: ${level === 'solid' ? 'var(--material-solid-border)' : 'transparent'};\n  --material-edge: ${level === 'solid' ? 'transparent' : 'var(--material-glass-edge)'};\n  --material-seam: ${level === 'solid' ? 'transparent' : 'var(--material-glass-seam)'};\n}\n`
  }
  css += material('glass', ':root, [data-material="glass"]')
  for (const level of ['glass', 'tinted', 'solid']) {
    if (level !== 'glass') css += material(level, `[data-material="${level}"]`)
    css += material(level, `[data-material="${level}"] [data-elevation="3"], [data-material="${level}"][data-elevation="3"]`, true)
  }
  // The default only: :where() keeps it at one attribute of specificity, so a nested
  // [data-material] (catalog frames, per-pane materials) still decides its strong layers.
  css += material('glass', ':where(:root:not([data-material])) [data-elevation="3"]', true)

  // Accessibility and resource constraints override every local material recipe, including
  // strong descendants. Important is confined to these mandatory fallback properties.
  function solid(selector, forced = false) {
    return `${selector} {\n  --material-background: ${forced ? 'Canvas' : 'var(--material-solid-fill)'} !important;\n  --material-backdrop: none !important;\n  --material-grain: 0 !important;\n  --material-border: ${forced ? 'ButtonText' : 'var(--material-solid-border)'} !important;\n  --material-edge: transparent !important;\n  --material-seam: transparent !important;\n}\n`
  }
  const triggers = ':is([data-reduce-transparency], [data-battery-saver], [data-gpu-compositing="off"], [data-theme$="-hc"])'
  css += solid(`${triggers}, ${triggers} :is([data-material], [data-elevation])`)
  css += `@media (prefers-reduced-transparency: reduce), (prefers-contrast: more) {\n${solid(':root, [data-material], [data-elevation]')}}\n`
  css += `@media (forced-colors: active) {\n${solid(':root, [data-material], [data-elevation]', true)}`
  css += ':root {\n'
  for (const token of defaults.filter(t => t.path[0] === 'color')) {
    const [, category, role] = token.path
    let value = category === 'background' ? 'Canvas' : category === 'border' ? 'ButtonText' : category === 'ring' ? 'Highlight' : 'CanvasText'
    if (category === 'background' && role === 'accent') value = 'Highlight'
    if (category === 'text' && role === 'on-accent') value = 'HighlightText'
    css += `  --${token.path.join('-')}: ${value} !important;\n`
  }
  return css + '}\n}\n'
}
