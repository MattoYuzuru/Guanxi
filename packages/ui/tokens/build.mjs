import StyleDictionary from 'style-dictionary'
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { resolveTokens, permutations, tokenRoot } from './resolve.mjs'
import { validateTokens } from './validate.mjs'

const header = '/* Generated by npm run tokens:build. Do not edit. */\n'
export const cssName = t => '--' + t.path.join('-')
export function cssValue(t) {
  const v = t.$value
  switch (t.$type) {
    case 'color': return `oklch(${v.components.join(' ')}${v.alpha === undefined ? '' : ` / ${v.alpha}`})`
    case 'dimension': case 'duration': return `${v.value}${v.unit}`
    case 'fontFamily': return (Array.isArray(v) ? v : [v]).map(n => n.includes(' ') ? JSON.stringify(n) : n).join(', ')
    case 'cubicBezier': return `cubic-bezier(${v.join(', ')})`
    case 'shadow': return (Array.isArray(v) ? v : [v]).map(s => [s.offsetX, s.offsetY, s.blur, s.spread].map(d => `${d.value}${d.unit}`).join(' ') + ` oklch(${s.color.components.join(' ')} / ${s.color.alpha ?? 1})`).join(', ')
    default: return String(v)
  }
}
const aliases = {
  canvas: 'color-background-primary', surface: 'color-background-secondary', inset: 'color-background-tertiary',
  foreground: 'color-text-primary', secondary: 'color-text-secondary', muted: 'color-text-tertiary',
  accent: 'color-background-accent', 'accent-foreground': 'color-text-on-accent',
  control: 'color-border-control', divider: 'color-border-primary', focus: 'color-ring-primary',
  warning: 'color-text-warning', danger: 'color-text-danger', success: 'color-text-success', info: 'color-text-info',
}
function themeCSS(flat) {
  const lines = ['  --color-*: initial;', '  --ease-*: initial;', '  --animate-*: initial;', '  --spacing-*: initial;', '  --text-*: initial;', '  --radius-*: initial;', '  --font-*: initial;']
  for (const [name, variable] of Object.entries(aliases)) lines.push(`  --color-${name}: var(--${variable});`)
  for (const t of flat.filter(t => t.path[0] === 'spacing' && t.path.length > 1)) lines.push(`  --spacing-${Number(t.path[1]) / 4}: var(${cssName(t)});`)
  lines.push('  --spacing: var(--spacing);')
  for (const t of flat.filter(t => t.name.startsWith('font.size.'))) lines.push(`  --text-${t.path[2]}: var(${cssName(t)});`)
  lines.push('  --text-body: var(--font-text-size);', '  --font-sans: var(--font-sans);', '  --font-mono: var(--font-mono);')
  for (const t of flat.filter(t => t.path[0] === 'border-radius')) lines.push(`  --radius-${t.path[1]}: var(${cssName(t)});`)
  for (const t of flat.filter(t => t.name.startsWith('motion.easing.'))) lines.push(`  --ease-${t.path[2]}: var(${cssName(t)});`)
  let output = header + `@theme inline {\n${lines.join('\n')}\n}\n`
  for (const t of flat.filter(t => t.name.startsWith('motion.duration.'))) {
    output += `@utility duration-${t.path[2]} { transition-duration: var(${cssName(t)}); }\n`
    output += `@utility delay-${t.path[2]} { transition-delay: var(${cssName(t)}); }\n`
  }
  return output
}

StyleDictionary.registerFormat({ name: 'guanxi/flat', format: ({ dictionary }) => JSON.stringify(dictionary.allTokens.map(t => {
  const path = t.path.filter(part => part !== '$root')
  return { name: path.join('.'), path, $type: t.$type, $value: t.$value, $description: t.$description }
})) })

export async function generate(options = {}) {
  const contexts = {}
  for (const modes of await permutations(options)) {
    const { tokens } = await resolveTokens(modes, options)
    validateTokens(tokens)
    // Style Dictionary owns alias resolution and deterministic platform formatting.
    const sd = new StyleDictionary({ tokens, usesDtcg: true, log: { verbosity: 'silent', errors: { brokenReferences: 'throw' } }, platforms: { flat: { transforms: [], files: [{ destination: 'flat.json', format: 'guanxi/flat' }] } } })
    const formatted = await sd.formatPlatform('flat')
    contexts[Object.values(modes).join('/')] = JSON.parse(formatted[0].output).sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)
  }
  const defaults = contexts['light/compact/full']
  function declarations(flat) {
    return flat.flatMap(t => t.$type === 'color' ? [`  ${cssName(t)}: ${t.$value.hex};`, `  ${cssName(t)}: ${cssValue(t)};`] : [`  ${cssName(t)}: ${cssValue(t)};`]).join('\n')
  }
  function diff(flat, base) {
    const map = new Map(base.map(t => [t.name, cssValue(t)]))
    return flat.filter(t => cssValue(t) !== map.get(t.name))
  }
  let css = header + '@import "../fonts/fonts.css";\n' + `:root {\n${declarations(defaults)}\n}\n`
  const theme = (name, selector) => `${selector} {\n${declarations(contexts[`${name}/compact/full`])}\n}\n`
  for (const name of ['light', 'dark', 'light-hc', 'dark-hc']) css += theme(name, `[data-theme="${name}"]${name === 'dark' ? ', :root.dark:not([data-theme])' : ''}`)
  const densityNames = new Set(['font.text.size', 'control.height', 'row.height', 'panel.padding', 'pane.gap'])
  for (const density of ['compact', 'comfortable']) css += `[data-density="${density}"] {\n${declarations(contexts[`light/${density}/full`].filter(t => densityNames.has(t.name)))}\n}\n`
  for (const motion of ['full', 'reduced']) css += `[data-motion="${motion}"] {\n${declarations(diff(contexts[`light/compact/${motion}`], defaults).length ? diff(contexts[`light/compact/${motion}`], defaults) : defaults.filter(t => t.name.startsWith('motion.')))}\n}\n`
  css += `@media (prefers-color-scheme: dark) {\n${theme('dark', ':root:not([data-theme]), :root[data-theme="system"]')} }\n`
  css += `@media (prefers-contrast: more) {\n${theme('light-hc', ':root:not([data-theme]), :root[data-theme="system"], :root[data-theme="light"]')}@media (prefers-color-scheme: dark) {\n${theme('dark-hc', ':root:not([data-theme]), :root[data-theme="system"]')} }\n${theme('dark-hc', ':root[data-theme="dark"]')} }\n`
  const reduced = diff(contexts['light/compact/reduced'], defaults)
  css += `@media (prefers-reduced-motion: reduce) {\n:root:not([data-motion="full"]) {\n${declarations(reduced)}\n}\n}\n`
  const material = (level, selector, strong = false) => `${selector} {\n  --material-background: color-mix(in srgb, var(--material-${level}-fill) calc(var(--material-${strong ? 'strong-' : ''}${level}-fill-opacity) * 100%), transparent);\n  --material-backdrop: blur(var(--material-${strong ? 'strong-' : ''}${level}-blur)) saturate(var(--material-${strong ? 'strong-' : ''}${level}-saturation));\n  --material-grain: var(--material-${level}-grain-opacity);\n  --material-border: var(--material-${level}-border);\n}\n`
  css += material('glass', ':root, [data-material="glass"]')
  for (const level of ['glass', 'tinted', 'solid']) {
    if (level !== 'glass') css += material(level, `[data-material="${level}"]`)
    css += material(level, `[data-material="${level}"] [data-elevation="3"], [data-material="${level}"][data-elevation="3"]`, true)
  }
  css += material('glass', ':root:not([data-material]) [data-elevation="3"]', true)
  css += material('solid', '[data-reduce-transparency], [data-battery-saver], [data-gpu-compositing="off"], [data-theme$="-hc"]')
  css += `@media (prefers-reduced-transparency: reduce), (prefers-contrast: more) {\n${material('solid', ':root')} }\n`
  css += '@media (forced-colors: active) {\n  :root { --material-background: Canvas; --material-backdrop: none; --material-grain: 0; --material-border: ButtonText; --color-background-primary: Canvas; --color-background-secondary: Canvas; --color-background-tertiary: Canvas; --color-background-accent: Highlight; --color-text-primary: CanvasText; --color-text-secondary: CanvasText; --color-text-tertiary: CanvasText; --color-text-on-accent: HighlightText; --color-border-primary: ButtonText; --color-border-control: ButtonText; --color-ring-primary: Highlight; }\n}\n'
  const values = Object.fromEntries(Object.entries(contexts).map(([key, flat]) => [key, Object.fromEntries(flat.map(t => [t.name, cssValue(t)]))]))
  const ts = '// Generated by npm run tokens:build. Do not edit.\n'
    + `export const tokens = ${JSON.stringify(values, null, 2)} as const\nexport type TokenName = keyof typeof tokens['light/compact/full']\nexport type TokenContext = keyof typeof tokens\nexport const cssVar = (name: TokenName): string => 'var(--' + name.replaceAll('.', '-') + ')'\n`
  const mcp = Object.fromEntries(['light', 'dark', 'light-hc', 'dark-hc'].map(theme => [theme, Object.fromEntries(contexts[`${theme}/compact/full`].filter(t => /^(color\.|font\.|border-radius\.|border-width\.)/.test(t.name)).map(t => [cssName(t), cssValue(t)]))]))
  const flatJSON = '{\n' + Object.entries(contexts).map(([key, tokens]) => `  ${JSON.stringify(key)}: [\n${tokens.map(token => '    ' + JSON.stringify(token)).join(',\n')}\n  ]`).join(',\n') + '\n}\n'
  return { 'tokens.css': css, 'theme.css': themeCSS(defaults), 'tokens.ts': ts, 'mcp-apps-variables.ts': '// Generated by npm run tokens:build. Do not edit.\nexport const mcpAppsVariables = ' + JSON.stringify(mcp, null, 2) + ' as const\n', 'tokens.flat.json': flatJSON }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const outputs = await generate()
  const destination = resolve(tokenRoot, '../generated')
  await mkdir(destination, { recursive: true })
  for (const [name, contents] of Object.entries(outputs)) await writeFile(resolve(destination, name), contents)
  process.stdout.write(JSON.stringify({ ok: true, files: Object.keys(outputs) }) + '\n')
}
